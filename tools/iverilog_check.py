#!/usr/bin/env python3
"""Three-way check: faultline CLI vs tools/ref_eval.py vs Icarus Verilog.

Usage: iverilog_check.py [--cli PATH] [--vectors N] [--seed S] file.bench...

For each circuit:
  1. make N seeded random input vectors (all 2^n vectors if 2^n <= N),
  2. convert the netlist to Verilog (bench_to_verilog.py) and write a
     testbench that loads the vectors with $readmemb, applies one, waits #10
     and prints the outputs,
  3. run iverilog + vvp, `faultline sim` and ref_eval.py on the same vectors,
  4. compare the settled outputs vector by vector.

Gate primitives have zero delay, so after #10 the outputs are settled; we
compare those final values, not waveforms. Exit status is 1 on any mismatch.
"""

import argparse
import random
import subprocess
import sys
import tempfile
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
import bench_to_verilog  # noqa: E402  (needs the sys.path line above)

TESTBENCH = """`timescale 1ns/1ns
module tb;
  reg  [0:{n_in_1}] vectors [0:{n_vec_1}];
  reg  [0:{n_in_1}] pi;
  wire [0:{n_out_1}] po;
  integer i;
  dut u_dut (.pi(pi), .po(po));
  initial begin
    $readmemb("vectors.mem", vectors);
    for (i = 0; i < {n_vec}; i = i + 1) begin
      pi = vectors[i];
      #10;
      $display("OUT %b", po);
    end
    $finish;
  end
endmodule
"""


def make_vectors(width, count, seed, name):
    if width <= 20 and 2 ** width <= count:
        return [format(v, f"0{width}b") for v in range(2 ** width)]
    # A string seed is deterministic across runs and Python versions, and the
    # circuit name in it gives each circuit its own sequence.
    rng = random.Random(f"{seed}:{name}")
    return ["".join(rng.choice("01") for _ in range(width)) for _ in range(count)]


def run(command, cwd=None):
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise RuntimeError(f"command failed: {' '.join(command)}\n{result.stderr}")
    return result.stdout


def iverilog_outputs(bench, vectors, n_inputs, n_outputs, workdir):
    (workdir / "dut.v").write_text(bench_to_verilog.to_verilog(str(bench), "dut"))
    (workdir / "vectors.mem").write_text("\n".join(vectors) + "\n")
    (workdir / "tb.v").write_text(TESTBENCH.format(
        n_in_1=n_inputs - 1, n_out_1=n_outputs - 1, n_vec=len(vectors), n_vec_1=len(vectors) - 1))
    run(["iverilog", "-g2005", "-o", "sim.vvp", "tb.v", "dut.v"], cwd=workdir)
    stdout = run(["vvp", "-n", "sim.vvp"], cwd=workdir)
    return [line[4:].strip() for line in stdout.splitlines() if line.startswith("OUT ")]


def check_circuit(bench, cli, count, seed):
    inputs, outputs, _ = bench_to_verilog.read_bench(str(bench))
    vectors = make_vectors(len(inputs), count, seed, bench.stem)
    with tempfile.TemporaryDirectory() as tmp:
        workdir = Path(tmp)
        vector_file = workdir / "vectors.txt"
        vector_file.write_text("# generated by iverilog_check.py\n" + "\n".join(vectors) + "\n")
        results = {
            "iverilog": iverilog_outputs(bench, vectors, len(inputs), len(outputs), workdir),
            "faultline": run([cli, "sim", str(bench), str(vector_file)]).split(),
            "ref_eval": run([sys.executable, str(TOOLS / "ref_eval.py"), str(bench),
                             str(vector_file)]).split(),
        }
    for tool, lines in results.items():
        if len(lines) != len(vectors):
            print(f"{bench.stem}: FAIL, {tool} printed {len(lines)} lines for {len(vectors)} vectors")
            return False
    for index, vector in enumerate(vectors):
        row = {tool: lines[index] for tool, lines in results.items()}
        if len(set(row.values())) != 1:
            print(f"{bench.stem}: MISMATCH at vector {index} ({vector}): {row}")
            return False
    print(f"{bench.stem}: {len(vectors)} vectors, {len(inputs)} inputs, {len(outputs)} outputs, "
          f"3-way match")
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("benches", nargs="+", type=Path)
    parser.add_argument("--cli", default=str(TOOLS.parent / "build" / "debug" / "faultline"))
    parser.add_argument("--vectors", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=1)
    args = parser.parse_args()

    version = run(["iverilog", "-V"]).splitlines()[0]
    print(f"# {version}; seed={args.seed}; vectors per circuit={args.vectors}")
    all_ok = True
    for bench in args.benches:
        all_ok = check_circuit(bench, args.cli, args.vectors, args.seed) and all_ok
    print("ALL MATCH" if all_ok else "SOME CIRCUITS FAILED")
    return 0 if all_ok else 1


if __name__ == "__main__":
    sys.exit(main())
